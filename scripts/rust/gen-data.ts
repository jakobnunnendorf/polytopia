/**
 * Generates engine/core/src/data_gen.rs from logic/engine/data.ts, so the
 * rules data has one source. Enum variants keep the order of data.ts (object
 * key order), because iteration order is behaviour: the greedy bot takes the
 * first best action.
 *
 *   node -r sucrase/register scripts/rust/gen-data.ts          # write
 *   node -r sucrase/register scripts/rust/gen-data.ts --check  # exit 1 if out of date
 */
import fs from "node:fs";
import path from "node:path";
import {
  BUILDS,
  CLANS,
  EMBARK_AS,
  FEEDS,
  MONUMENTS,
  RAFT_UPGRADES,
  TECHS,
  TRIBE_ONLY_BUILDS,
  TRIBE_ONLY_UNITS,
  UNITS,
} from "../../logic/engine/data";

const ROOT = path.resolve(__dirname, "../..");
const OUT = path.join(ROOT, "engine/core/src/data_gen.rs");

const pascal = (id: string) => id.charAt(0).toUpperCase() + id.slice(1);

/** the members of a string-literal union type in a source file */
function unionOf(file: string, name: string): string[] {
  const src = fs.readFileSync(path.join(ROOT, file), "utf8");
  const m = src.match(new RegExp(`export type ${name} =([^;]*);`, "s"));
  if (!m) throw new Error(`type ${name} not found in ${file}`);
  return [...m[1].replace(/\/\/[^\n]*|\/\*[\s\S]*?\*\//g, "").matchAll(/"([^"]+)"/g)].map((x) => x[1]);
}

const TERRAINS = unionOf("logic/engine/types.ts", "Terrain");
const RESOURCES = unionOf("logic/engine/types.ts", "ResourceId");
const SKILLS = unionOf("logic/engine/data.ts", "Skill");
const KINDS = ["building", "harvest", "road", "bridge", "temple", "monument", "destroy", "embassy"];
const MOD_KEYS = ["mountain", "forest", "fruit", "crop", "animal", "fish", "metal", "water", "spores", "aquaCrop"];
const REWARDS = ["workshop", "explorer", "cityWall", "resources", "populationGrowth", "borderGrowth", "park", "superUnit"];
const TASKS = [...new Set(Object.keys(MONUMENTS))];

const unitIds = Object.keys(UNITS);
const techIds = TECHS.map((t) => t.id);
const buildIds = Object.keys(BUILDS);
const tribeIds = CLANS.map((c) => c.id);

function enumOf(name: string, ids: string[], doc: string): string {
  const v = ids.map(pascal);
  const all = v.map((x) => `${name}::${x}`).join(", ");
  return `/// ${doc}
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
#[repr(u8)]
pub enum ${name} {
${v.map((x, i) => `    ${x} = ${i},`).join("\n")}
}

impl ${name} {
    pub const COUNT: usize = ${ids.length};
    pub const ALL: [${name}; ${ids.length}] = [${all}];
    #[inline]
    pub fn idx(self) -> usize {
        self as usize
    }
    #[inline]
    pub fn from_idx(i: usize) -> ${name} {
        Self::ALL[i]
    }
    pub fn id(self) -> &'static str {
        [${ids.map((x) => JSON.stringify(x)).join(", ")}][self as usize]
    }
    pub fn from_id(s: &str) -> Option<${name}> {
        match s {
${ids.map((x) => `            ${JSON.stringify(x)} => Some(${name}::${pascal(x)}),`).join("\n")}
            _ => None,
        }
    }
}
`;
}

const opt = <T,>(x: T | null | undefined, f: (x: T) => string) => (x === null || x === undefined ? "None" : `Some(${f(x)})`);
const num = (x: number) => (Number.isInteger(x) ? `${x}.0` : String(x));
const U = (x: string) => {
  if (!unitIds.includes(x)) throw new Error(`unknown unit ${x}`);
  return `UnitType::${pascal(x)}`;
};
const T = (x: string) => {
  if (!techIds.includes(x)) throw new Error(`unknown tech ${x}`);
  return `Tech::${pascal(x)}`;
};
const B = (x: string) => {
  if (!buildIds.includes(x)) throw new Error(`unknown build ${x}`);
  return `Build::${pascal(x)}`;
};
const R = (x: string) => `Resource::${pascal(x)}`;
const TR = (x: string) => `Terrain::${pascal(x)}`;
const mask = (xs: string[], all: string[], what: string) =>
  xs.length === 0
    ? "0"
    : xs
        .map((x) => {
          const i = all.indexOf(x);
          if (i < 0) throw new Error(`unknown ${what} ${x}`);
          return `(1 << ${i})`;
        })
        .join(" | ");

let out = `// @generated by scripts/rust/gen-data.ts from logic/engine/data.ts. Do not edit by hand.
#![allow(clippy::all)]

${enumOf("Terrain", TERRAINS, "tile terrain (types.ts Terrain)")}
${enumOf("Resource", RESOURCES, "tile resource (types.ts ResourceId)")}
${enumOf("Skill", SKILLS, "unit skill (data.ts Skill); a unit's skills are a bit mask over this enum")}
${enumOf("UnitType", unitIds, "unit type (data.ts UNITS, in key order)")}
${enumOf("Tech", techIds, "technology (data.ts TECHS, in order)")}
${enumOf("Build", buildIds, "tile action or building (data.ts BUILDS, in key order, monuments last)")}
${enumOf("BuildKind", KINDS, "kind of a build (data.ts BuildDef.kind)")}
${enumOf("Tribe", tribeIds, "tribe (data.ts CLANS, in order)")}
${enumOf("ModKey", MOD_KEYS, "map generation modifier key (data.ts ClanDef.mod)")}
${enumOf("Reward", REWARDS, "city level-up reward (data.ts rewardOptions)")}
${enumOf("Task", TASKS, "task that earns a monument (data.ts MONUMENTS keys)")}

pub struct UnitDef {
    pub id: UnitType,
    pub cost: i32,
    pub trainable: bool,
    /// None for boats whose HP is the passenger's
    pub hp: Option<f64>,
    pub attack: f64,
    pub defence: f64,
    pub movement: i32,
    pub range: i32,
    /// bit mask over Skill
    pub skills: u64,
    /// the skills in data.ts order
    pub skill_list: &'static [Skill],
    pub tech: Option<Tech>,
    pub naval: bool,
    pub ice_movement: Option<i32>,
}

impl UnitDef {
    #[inline]
    pub fn has(&self, s: Skill) -> bool {
        self.skills & (1u64 << (s as u32)) != 0
    }
}

pub static UNITS: [UnitDef; ${unitIds.length}] = [
${unitIds
  .map((id) => {
    const d = UNITS[id];
    return `    UnitDef { id: ${U(id)}, cost: ${d.cost}, trainable: ${d.trainable}, hp: ${opt(d.hp, num)}, attack: ${num(d.attack)}, defence: ${num(d.defence)}, movement: ${d.movement}, range: ${d.range}, skills: ${mask(d.skills, SKILLS, "skill")}, skill_list: &[${d.skills.map((s) => `Skill::${pascal(s)}`).join(", ")}], tech: ${opt(d.tech, T)}, naval: ${d.naval}, ice_movement: ${opt(d.iceMovement, String)} },`;
  })
  .join("\n")}
];

pub struct TechDef {
    pub id: Tech,
    pub tier: i32,
    pub parent: Option<Tech>,
}

pub static TECHS: [TechDef; ${techIds.length}] = [
${TECHS.map((t) => `    TechDef { id: ${T(t.id)}, tier: ${t.tier}, parent: ${opt(t.parent, T)} },`).join("\n")}
];

pub struct BuildDef {
    pub id: Build,
    pub cost: i32,
    /// None for monuments (tech "" in data.ts)
    pub tech: Option<Tech>,
    pub kind: BuildKind,
    /// bit mask over Terrain
    pub terrain: u8,
    pub resource: Option<Resource>,
    pub pop: i32,
    pub gain: Option<i32>,
    pub next_to: &'static [Build],
    pub next_to_terrain: Option<Terrain>,
    pub one_per_city: bool,
}

impl BuildDef {
    #[inline]
    pub fn allows(&self, t: Terrain) -> bool {
        self.terrain & (1u8 << (t as u32)) != 0
    }
}

pub static BUILDS: [BuildDef; ${buildIds.length}] = [
${buildIds
  .map((id) => {
    const d = BUILDS[id];
    return `    BuildDef { id: ${B(id)}, cost: ${d.cost}, tech: ${d.tech ? `Some(${T(d.tech)})` : "None"}, kind: BuildKind::${pascal(d.kind)}, terrain: ${mask(d.terrain, TERRAINS, "terrain")}, resource: ${opt(d.resource, R)}, pop: ${d.pop}, gain: ${opt(d.gain, String)}, next_to: &[${(d.nextTo ?? []).map(B).join(", ")}], next_to_terrain: ${opt(d.nextToTerrain, TR)}, one_per_city: ${!!d.onePerCity} },`;
  })
  .join("\n")}
];

pub struct TribeDef {
    pub id: Tribe,
    pub start_tech: Option<Tech>,
    pub start_unit: UnitType,
    pub start_stars: i32,
    pub capital_level: i32,
    /// indexed by ModKey; None = not set (data.ts leaves the key out)
    pub mods: [Option<f64>; ${MOD_KEYS.length}],
    pub start_resources: &'static [Resource],
    pub special: bool,
    /// data.ts superUnit; None = not set (superUnitFor gives "giant")
    pub super_unit: Option<UnitType>,
    /// in data.ts key order; None = disabled
    pub unit_replacements: &'static [(UnitType, Option<UnitType>)],
    pub extra_units: &'static [UnitType],
    pub build_replacements: &'static [(Build, Option<Build>)],
    pub extra_builds: &'static [Build],
}

pub static TRIBES: [TribeDef; ${tribeIds.length}] = [
${CLANS.map((c) => {
  const mods = MOD_KEYS.map((k) => opt((c.mod as Record<string, number>)[k], num)).join(", ");
  const ur = Object.entries(c.unitReplacements ?? {}).map(([a, b]) => `(${U(a)}, ${opt(b, U)})`).join(", ");
  const br = Object.entries(c.buildReplacements ?? {}).map(([a, b]) => `(${B(a)}, ${opt(b, B)})`).join(", ");
  return `    TribeDef { id: Tribe::${pascal(c.id)}, start_tech: ${opt(c.startTech, T)}, start_unit: ${U(c.startUnit)}, start_stars: ${c.startStars}, capital_level: ${c.capitalLevel}, mods: [${mods}], start_resources: &[${c.startResources.map(R).join(", ")}], special: ${!!c.special}, super_unit: ${opt(c.superUnit, U)}, unit_replacements: &[${ur}], extra_units: &[${(c.extraUnits ?? []).map(U).join(", ")}], build_replacements: &[${br}], extra_builds: &[${(c.extraBuilds ?? []).map(B).join(", ")}] },`;
}).join("\n")}
];

/// data.ts TRIBE_ONLY_UNITS
pub static TRIBE_ONLY_UNITS: &[UnitType] = &[${[...TRIBE_ONLY_UNITS].map(U).join(", ")}];
/// data.ts TRIBE_ONLY_BUILDS
pub static TRIBE_ONLY_BUILDS: &[Build] = &[${[...TRIBE_ONLY_BUILDS].map(B).join(", ")}];
/// data.ts EMBARK_AS: land unit -> boat it becomes (default raft)
pub static EMBARK_AS: &[(UnitType, UnitType)] = &[${Object.entries(EMBARK_AS).map(([a, b]) => `(${U(a)}, ${U(b)})`).join(", ")}];
/// data.ts RAFT_UPGRADES
pub static RAFT_UPGRADES: &[UnitType] = &[${RAFT_UPGRADES.map(U).join(", ")}];
/// data.ts FEEDS: feeder -> (leveling building, population per level)
pub static FEEDS: &[(Build, Build, i32)] = &[${Object.entries(FEEDS).map(([a, f]) => `(${B(a)}, ${B(f.building)}, ${f.popPerLevel})`).join(", ")}];
/// data.ts MONUMENTS: task -> monument
pub static MONUMENTS: &[(Task, Build)] = &[${Object.entries(MONUMENTS).map(([t, m]) => `(Task::${pascal(t)}, ${B(m)})`).join(", ")}];
`;

const check = process.argv.includes("--check");
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (check) {
  if (prev !== out) {
    console.error("engine/core/src/data_gen.rs is out of date: run node -r sucrase/register scripts/rust/gen-data.ts");
    process.exit(1);
  }
  console.log("data_gen.rs up to date");
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${unitIds.length} units, ${techIds.length} techs, ${buildIds.length} builds, ${tribeIds.length} tribes, ${SKILLS.length} skills`);
}
